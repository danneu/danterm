// The F3 admission probe for doc 31: does admitting a scrolled-off row into an open logical
// line cost more than today's pack-one-record-per-display-row admission?
//
// Two arms, one process, interleaved ABBA. **Baseline** reproduces
// `Terminal.swift#appendToScrollback`: `PackedRetainedRow.pack` per display row, an append into
// the retained buffer, and the two accumulations that call site performs (charged bytes and
// stored cells). **Candidate** is doc 31's open-line rule with `F4`'s corrected semantics: the
// row's cells are appended to the arena's open record at the write cursor, `.spacerHead` cells
// are dropped (the store never held one), a row that is not soft-wrapped closes the record and
// writes its header bits, and mutation only ever touches the tail. Both arms admit the *same*
// engine-produced rows, and a readback outside every timed region proves they hold the same
// display rows cell for cell.
//
// Belongs here: the two admitters, the four content classes, and the calibration and gates that
// decide whether a run may be quoted. Does not belong here: a threshold or a verdict (those are
// `31/D1`'s Part B rule for F3, frozen at `d6c83b0` before this file existed), the read walk
// (`TerminalLogicalLineReadProbe.swift` owns it), or the counting pass
// (`TerminalLogicalLineIndexProbe.swift` owns it).
//
// **Nothing in F1's or F2's files is edited by this finding.** What is reused from them is the
// harness they already own -- `RetainedStimulus`, `interleavedRounds`, `ArmRound`, `median`,
// `percentile`, `logicalLines`, `probeKind`, `loadAverageDescription`. What is *not* reused is
// `buildStimulus`: F3 needs two content classes F1's frozen `LogicalLineContentClass` does not
// have, and adding a case to that enum would change `allCases` and so change what F1's own
// measurement runs. The stimulus builder below is therefore F3's own, and it stores rows
// materialized to full width because that is the shape production admission actually receives
// from the live grid -- `pack`'s first walk covers every column, and charging the baseline a
// shorter walk than production pays would understate it.
//
// Not part of the `just test` gate. Every measurement is skipped unless
// `DANTERM_LOGICAL_LINE_PROBE` is set. Run it as:
//
//     DANTERM_LOGICAL_LINE_PROBE=1 swift test -c release --package-path lib/TerminalCore \
//       --filter TerminalLogicalLineAdmissionProbe
//
// Release matters: the bound in `31/D1`'s F3 rule is derived from release-build shares.
